#ifndef SYS_IOCCOM_H
#include <sys/ioccom.h>
#endif

/* sizes of structures in net/if.h and net/if_arp.h, so this header can
 * stand alone */
#define __OPENSOCKET_IFREQ_SIZE		32
#define __OPENSOCKET_IFCONF_SIZE	8
#define __OPENSOCKET_IFALIASREQ_SIZE	64
#define __OPENSOCKET_ARPREQ_SIZE	36

#define SIOCSHIWAT		_IOW('s', 0, LONG)
#define SIOCGHIWAT		_IOR('s', 1, LONG)
#define SIOCSLOWAT		_IOW('s', 2, LONG)
#define SIOCGLOWAT		_IOR('s', 3, LONG)
#define SIOCATMARK		_IOR('s', 7, LONG)	/* at the urgent mark? */
#define SIOCSPGRP		_IOW('s', 8, LONG)
#define SIOCGPGRP		_IOR('s', 9, LONG)

#define __OPENSOCKET_IFW(n)	_IOC(IOC_IN, 'i', (n), __OPENSOCKET_IFREQ_SIZE)
#define __OPENSOCKET_IFWR(n)	_IOC(IOC_INOUT, 'i', (n), __OPENSOCKET_IFREQ_SIZE)
#define SIOCSIFADDR		__OPENSOCKET_IFW(12)
#define OSIOCGIFADDR		__OPENSOCKET_IFWR(13)
#define SIOCGIFADDR		__OPENSOCKET_IFWR(33)
#define SIOCSIFDSTADDR		__OPENSOCKET_IFW(14)
#define OSIOCGIFDSTADDR		__OPENSOCKET_IFWR(15)
#define SIOCGIFDSTADDR		__OPENSOCKET_IFWR(34)
#define SIOCSIFFLAGS		__OPENSOCKET_IFW(16)
#define SIOCGIFFLAGS		__OPENSOCKET_IFWR(17)
#define OSIOCGIFBRDADDR		__OPENSOCKET_IFWR(18)
#define SIOCGIFBRDADDR		__OPENSOCKET_IFWR(35)
#define SIOCSIFBRDADDR		__OPENSOCKET_IFW(19)
#define OSIOCGIFCONF		_IOC(IOC_INOUT, 'i', 20, __OPENSOCKET_IFCONF_SIZE)
#define SIOCGIFCONF		_IOC(IOC_INOUT, 'i', 36, __OPENSOCKET_IFCONF_SIZE)
#define OSIOCGIFNETMASK		__OPENSOCKET_IFWR(21)
#define SIOCGIFNETMASK		__OPENSOCKET_IFWR(37)
#define SIOCSIFNETMASK		__OPENSOCKET_IFW(22)
#define SIOCGIFMETRIC		__OPENSOCKET_IFWR(23)
#define SIOCSIFMETRIC		__OPENSOCKET_IFW(24)
#define SIOCDIFADDR		__OPENSOCKET_IFW(25)
#define SIOCAIFADDR		_IOC(IOC_IN, 'i', 26, __OPENSOCKET_IFALIASREQ_SIZE)
#define SIOCADDMULTI		__OPENSOCKET_IFW(49)
#define SIOCDELMULTI		__OPENSOCKET_IFW(50)
#define SIOCSIFMTU		__OPENSOCKET_IFW(127)
#define SIOCGIFMTU		__OPENSOCKET_IFWR(126)
#define SIOCSIFASYNCMAP		__OPENSOCKET_IFW(125)
#define SIOCGIFASYNCMAP		__OPENSOCKET_IFWR(124)
#define SIOCSARP		_IOC(IOC_IN, 'I', 30, __OPENSOCKET_ARPREQ_SIZE)
#define SIOCGARP		_IOC(IOC_INOUT, 'I', 38, __OPENSOCKET_ARPREQ_SIZE)
#define SIOCDARP		_IOC(IOC_IN, 'I', 32, __OPENSOCKET_ARPREQ_SIZE)

#endif /* SYS_SOCKIO_H */
